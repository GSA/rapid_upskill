def cell(text: str, label: str) -> str:
    """The value cell of the metadata table row that starts with `| label |`."""
    prefix = f"| {label} | "
    rows = [line for line in text.split("\n") if line.startswith(prefix)]
    if len(rows) != 1:
        raise AssertionError(f"expected one {label!r} row, found {len(rows)}")
    return rows[0][len(prefix) : -len(" |")]


