def put(base: Path, rel: str, text: str, eol: str = "\n") -> None:
    """Write UTF-8 text with the given line ending, creating folders."""
    path = base / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.replace("\n", eol).encode("utf-8"))


def build_fixture(base: Path, eol: str = "\n") -> None:
    """A minimal repository: one prompt, two scripts, one image, two READMEs."""
    put(base, "docs/_config.yml", CONFIG, eol)
    put(base, "docs/index.md", "---\n" + INDEX_PAGE + "---\n\n# Home\n", eol)
    put(base, "docs/stage-1/search.md", STAGE_PAGE, eol)
    put(base, "prompts/s1/search-plan.md", PROMPT, eol)
    put(base, "prompts/README.md", "# Prompts\n", eol)
    put(base, "scripts/s1/search_plan.py", SCRIPT, eol)
    put(base, "scripts/common/text_helper.py", HELPER, eol)
    put(base, "images/README.md", "# Images\n", eol)
    (base / "images").mkdir(exist_ok=True)
    (base / "images" / "diagram.svg").write_bytes(SVG)


def snapshot(base: Path) -> dict[str, str]:
    """Map every path under base to a SHA-256 (or 'dir')."""
    snap = {}
    for path in sorted(base.rglob("*")):
        rel = path.relative_to(base).as_posix()
        if path.is_dir():
            snap[rel] = "dir"
        else:
            snap[rel] = hashlib.sha256(path.read_bytes()).hexdigest()
    return snap


def run_cli(base: Path, *args: str) -> subprocess.CompletedProcess[str]:
    """Run sync.py with --root and the fixture as the working directory."""
    return subprocess.run(  # nosec B603
        [sys.executable, "-B", str(SYNC), "--root", str(base), *args],
        capture_output=True,
        text=True,
        check=False,
        cwd=base,
    )


def page(outputs: dict[str, bytes], rel: str) -> str:
    return outputs[rel].decode("utf-8")


def with_body(body: str) -> str:
    """The fixture prompt as P-S1-05 with a new body that uses one placeholder."""
    text = PROMPT.replace('"P-S1-04"', '"P-S1-05"').replace(', "SOURCE_LIST"', "")
    old = (
        "Plan a search for objective {{OBJECTIVE_ID}}.\n"
        "Use only these sources: {{SOURCE_LIST}}."
    )
    return text.replace(old, body)


class FixtureCase(unittest.TestCase):
    """Each test gets its own fixture repository in a temporary directory."""

    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        build_fixture(self.root)

    def read(self, rel: str) -> str:
        return (self.root / rel).read_text(encoding="utf-8")

    def edit(self, rel: str, old: str, new: str) -> None:
        text = self.read(rel)
        self.assertIn(old, text)
        put(self.root, rel, text.replace(old, new, 1))

    def outputs(self) -> dict[str, bytes]:
        return sync.compute_outputs(self.root)

    def cli_ok(self, *args: str) -> subprocess.CompletedProcess[str]:
        proc = run_cli(self.root, *args)
        self.assertEqual(proc.returncode, 0, proc.stderr)
        return proc

    def cli_exit2(self, *args: str) -> str:
        """Run the CLI, expect exit 2, no output and no traceback; return stderr."""
        before = snapshot(self.root)
        proc = run_cli(self.root, *args)
        self.assertEqual(proc.returncode, 2, proc.stdout)
        self.assertEqual(proc.stdout, "")
        self.assertNotIn("Traceback", proc.stderr)
        self.assertEqual(snapshot(self.root), before)
        return proc.stderr


