    def test_raw_block_wraps_the_whole_body(self) -> None:
        outputs = self.outputs()
        for rel in EXPECTED_KEYS:
            if not rel.endswith(".md"):
                continue
            with self.subTest(rel=rel):
                text = page(outputs, rel)
                self.assertEqual(text.count("{% raw %}"), 1)
                self.assertEqual(text.count("{% endraw %}"), 1)
                start = text.index("{% raw %}")
                end = text.index("{% endraw %}")
                before, after = text[:start], text[end + len("{% endraw %}") :]
                self.assertNotIn("{{", before)
                self.assertNotIn("{%", before)
                self.assertEqual(after, "\n")
                self.assertGreater(text.index("\n# "), start)
                self.assertLess(text.rindex("\n#"), end)
        text = page(outputs, "docs/prompts/s1/p-s1-04.md")
        start, end = text.index("{% raw %}"), text.index("{% endraw %}")
        self.assertLess(start, text.index("{{OBJECTIVE_ID}}"))
        self.assertGreater(end, text.rindex("{{SOURCE_LIST}}"))

    def test_triple_backtick_block_in_prompt_is_fenced_correctly(self) -> None:
        body = (
            "Return this JSON:\n"
            "```json\n"
            '{"objective": "{{OBJECTIVE_ID}}"}\n'
            "```\n"
            "Nothing else."
        )
        put(
            self.root,
            "prompts/s1/json-plan.md",
            with_body(body),
        )
        text = page(self.outputs(), "docs/prompts/s1/p-s1-05.md")
        self.assertIn("\n## Prompt\n\n````text\n" + body + "\n````\n", text)
        fences = [f for f in sitelib.find_fences(text) if f.marker == "````"]
        self.assertEqual(len(fences), 1)
        self.assertEqual(fences[0].lang, "text")
        self.assertEqual(fences[0].content, body)

