    def test_default_root_is_two_levels_above_the_script(self) -> None:
        site = self.root / "scripts" / "site"
        site.mkdir(parents=True)
        for name in ("sync.py", "sitelib.py"):
            (site / name).write_bytes((SITE_DIR / name).read_bytes())
        with tempfile.TemporaryDirectory() as elsewhere:
            proc = subprocess.run(  # nosec B603
                [sys.executable, "-B", str(site / "sync.py")],
                capture_output=True,
                text=True,
                check=False,
                cwd=elsewhere,
            )
        self.assertEqual(proc.returncode, 0, proc.stderr)
