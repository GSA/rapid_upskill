class Fixture:
    """A small clean repository, built under a temporary directory."""

    def __init__(self, base: Path) -> None:
        self.root = base / "repo"
        self.generated: dict[str, bytes] = {}
        self.write("docs/_config.yml", 'title: "Fixture"\nbaseurl: "/fixture"\n')
        self.write("docs/index.md", HOME)
        self.write("docs/s1-1-example.md", STAGE)
        self.write("docs/_includes/footer_custom.html", FOOTER)
        self.write("images/flow.svg", SVG)
        self.set_generated("docs/assets/images/flow.svg", SVG)
        for rel, text in GENERATED.items():
            self.set_generated(rel, text)
        self.write("prompts/s1/example.md", PROMPT)
        self.write("scripts/s1/example.py", SCRIPT)
        self.write("README.md", "Template file.\n")
        self.write("CONTRIBUTING.md", "Template file.\n")

    def path(self, rel: str) -> Path:
        return self.root / rel

    def write(self, rel: str, text: str) -> Path:
        return self.write_bytes(rel, text.encode("utf-8"))

    def write_bytes(self, rel: str, data: bytes) -> Path:
        path = self.path(rel)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return path

    def set_generated(self, rel: str, text: str) -> None:
        """Write a generated file and record it as the expected sync output."""
        self.write(rel, text)
        self.generated[rel] = text.encode("utf-8")

    def read(self, rel: str) -> str:
        return self.path(rel).read_bytes().decode("utf-8")

    def edit(self, rel: str, old: str, new: str) -> None:
        text = self.read(rel)
        if old not in text:
            raise AssertionError(f"{old!r} not found in {rel}")
        self.write(rel, text.replace(old, new, 1))

    def line(self, rel: str, needle: str) -> int:
        """1-based number of the first line of the file that holds needle."""
        for number, line in enumerate(self.read(rel).split("\n"), 1):
            if needle in line:
                return number
        raise AssertionError(f"{needle!r} not found in {rel}")

    def append(self, rel: str, text: str) -> int:
        """Append a blank line and text; return the line number of the text."""
        before = self.read(rel)
        self.write(rel, before + "\n" + text + "\n")
        return before.count("\n") + 2

    def remove(self, rel: str) -> None:
        self.path(rel).unlink()


class FakeSync(types.ModuleType):
    """Stands in for sync.py; compute_outputs calls the given provider."""

    def __init__(self, provider: Callable[[], Any]) -> None:
        super().__init__("sync")
        self._provider = provider

    def compute_outputs(self, root: Path) -> Any:
        del root
        return self._provider()


class CheckCase(unittest.TestCase):
    """Builds a clean fixture and a fake sync for every test."""

    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.base = Path(tmp.name)
        self.fx = Fixture(self.base)
        self.install_sync(lambda: dict(self.fx.generated))

    def install_sync(self, provider: Callable[[], Any]) -> None:
        saved = sys.modules.get("sync")
        self.addCleanup(self.restore_sync, saved)
        sys.modules["sync"] = FakeSync(provider)

    @staticmethod
    def restore_sync(saved: types.ModuleType | None) -> None:
        if saved is None:
            sys.modules.pop("sync", None)
        else:
            sys.modules["sync"] = saved

    def findings(self, forbidden: Path | None = None) -> list[sitelib.Finding]:
        return check.run(self.fx.root, forbidden)

    def expect(
        self, *expected: str, forbidden: Path | None = None
    ) -> list[sitelib.Finding]:
        """Assert the exact set of 'SEV path:line RULE' keys; return findings."""
        found = self.findings(forbidden)
        actual = {f"{f.severity} {f.path}:{f.line} {f.rule}" for f in found}
        self.assertEqual(actual, set(expected), "\n".join(map(str, found)))
        return found

    def run_main(
        self, *argv: str, environ: dict[str, str] | None = None
    ) -> tuple[int, str, str]:
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = check.main(list(argv), environ={} if environ is None else environ)
        return code, out.getvalue(), err.getvalue()


