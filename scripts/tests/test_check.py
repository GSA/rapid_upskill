def generated_page(
    title: str, nav: int, parent: str, grand: str, source: str, body: str
) -> str:
    """A page shaped like sync output (plan S7): raw block around the body."""
    lines = ["---", f'title: "{title}"']
    if parent:
        lines.append(f'parent: "{parent}"')
    if grand:
        lines.append(f'grand_parent: "{grand}"')
    lines += [f"nav_order: {nav}", "generated: true", "---"]
    lines += [f"<!-- GENERATED by scripts/site/sync.py from {source}. Do not edit. -->"]
    lines += ["{% raw %}", "", f"# {title}", "", body.rstrip("\n"), "{% endraw %}", ""]
    return "\n".join(lines)


