class HelperTests(unittest.TestCase):
    def test_strip_raw_keeps_length_and_newlines(self) -> None:
        text = "a {% raw %}{{x}}\n{% endraw %} b {{y}}\nc"
        stripped, problems = check.strip_raw(text)
        self.assertEqual(problems, [])
        self.assertEqual(len(stripped), len(text))
        self.assertEqual(stripped.count("\n"), text.count("\n"))
        self.assertNotIn("{{x}}", stripped)
        self.assertIn("{{y}}", stripped)

    def test_raw_inside_raw_is_literal_text(self) -> None:
        stripped, problems = check.strip_raw("{% raw %} {% raw %} {{x}} {% endraw %} z")
        self.assertEqual(problems, [])
        self.assertNotIn("{{", stripped)

    def test_email_search_matches_the_shared_pattern(self) -> None:
        samples = [  # "#" stands for the at sign, so no address sits in this file
            "a#example.com",
            "x a.b#c.de, y#z.org. and mail:John.Doe+tag#sub.example.co.uk!",
            "#handle a# ## a#b a#b.c no email at all",
            "two: p#one.io q#two.io",
        ]
        for line in (sample.replace("#", "@") for sample in samples):
            with self.subTest(line=line):
                expected = [m.group() for m in sitelib.EMAIL_RE.finditer(line)]
                self.assertEqual(check.emails(line), expected)

    def test_very_long_lines_stay_fast(self) -> None:
        started = time.perf_counter()
        for line in ("a" * 300000, "a" * 300000 + "@", "a@" * 100000):
            check.public_hits(line, True)
        self.assertLess(time.perf_counter() - started, 10)

    def test_sources_are_clean_for_the_public_scan(self) -> None:
        needles = ["/Us" + "ers/", "/ho" + "me/", "C:\\Us" + "ers\\", "file:" + "///"]
        for path in (SITE_DIR / "check.py", Path(__file__)):
            text = path.read_text(encoding="utf-8")
            with self.subTest(file=path.name):
                for pattern in sitelib.SECRET_PATTERNS:
                    self.assertIsNone(pattern.search(text), pattern.pattern)
                for match in sitelib.EMAIL_RE.finditer(text):
                    self.assertTrue(sitelib.email_allowed(match.group()), match.group())
                for needle in needles:
                    self.assertNotIn(needle, text)
                self.assertIn("CC0-1.0", text)


class CliTests(unittest.TestCase):
    """Runs a copy of the tool beside a fake sync.py, so exit codes are exact."""

    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.base = Path(tmp.name)
        self.fx = Fixture(self.base)
        self.tool = self.base / "tool"
        self.tool.mkdir()
        for name in ("check.py", "sitelib.py"):
            shutil.copy2(SITE_DIR / name, self.tool / name)
        (self.tool / "sync.py").write_text(FAKE_SYNC_ECHO, encoding="utf-8")

    def cli(
        self, *args: str, script: Path | None = None, env: dict[str, str] | None = None
    ) -> "subprocess.CompletedProcess[str]":
        environ = {k: v for k, v in os.environ.items() if k != check.FORBIDDEN_ENV}
        environ["PYTHONDONTWRITEBYTECODE"] = "1"
        environ.update(env or {})
        command = [sys.executable, "-B", str(script or self.tool / "check.py"), *args]
        return subprocess.run(  # nosec B603
            command,
            capture_output=True,
            text=True,
            check=False,
            env=environ,
            cwd=self.base,
        )

    def test_exit_0_on_a_clean_repository(self) -> None:
        done = self.cli("--root", str(self.fx.root))
        self.assertEqual(done.returncode, 0, done.stdout + done.stderr)
        self.assertEqual(done.stdout, "check: 0 errors, 0 warnings\n")
        self.assertEqual(done.stderr, check.NOTICE + "\n")

    def test_exit_1_on_an_error_and_lines_are_sorted(self) -> None:
        self.fx.edit("docs/index.md", 'status: "draft"\n', "")
        self.fx.append("docs/s1-1-example.md", "[a](missing.md)")
        self.fx.append("docs/s1-1-example.md", "Path " + user_path())
        done = self.cli("--root", str(self.fx.root))
        self.assertEqual(done.returncode, 1)
        lines = done.stdout.splitlines()
        self.assertEqual(lines[-1], "check: 3 errors, 0 warnings")
        keys = []
        for text in lines[:-1]:
            location, rule = text.split(" ")[:2]
            path, _, number = location.rpartition(":")
            keys.append((path, int(number), rule))
        self.assertEqual(keys, sorted(keys))
        self.assertEqual([k[2] for k in keys], ["R01", "R04", "R10"])

    def test_exit_0_with_warnings_only(self) -> None:
        self.fx.append("docs/s1-1-example.md", "#### Too deep")
        done = self.cli("--root", str(self.fx.root))
        self.assertEqual(done.returncode, 0)
        self.assertTrue(done.stdout.endswith("check: 0 errors, 1 warnings\n"))

    def test_exit_2_for_a_bad_root(self) -> None:
        done = self.cli("--root", str(self.base / "nowhere"))
        self.assertEqual((done.returncode, done.stdout), (2, ""))
        self.assertIn("check:", done.stderr)
        empty = self.base / "empty"
        empty.mkdir()
        self.assertEqual(self.cli("--root", str(empty)).returncode, 2)

    def test_exit_2_for_an_unreadable_list(self) -> None:
        done = self.cli(
            "--root", str(self.fx.root), "--extra-forbidden", str(self.base / "no.txt")
        )
        self.assertEqual((done.returncode, done.stdout), (2, ""))
        self.assertNotIn(check.NOTICE, done.stderr)

    def test_exit_2_for_unknown_options(self) -> None:
        self.assertEqual(self.cli("--nope").returncode, 2)

    def test_exit_2_for_a_page_that_is_not_utf8(self) -> None:
        self.fx.write_bytes("docs/bad.md", b"\xff\xfe not text")
        done = self.cli("--root", str(self.fx.root))
        self.assertEqual((done.returncode, done.stdout), (2, ""))
        self.assertIn("docs/bad.md", done.stderr)

    def test_private_terms_through_the_command_line(self) -> None:
        term = "zq" + "xv" + "plum"
        line = self.fx.append("docs/index.md", "About " + term + " here.")
        terms = self.base / "terms.txt"
        terms.write_text(term + "\n", encoding="utf-8")
        done = self.cli("--root", str(self.fx.root), "--extra-forbidden", str(terms))
        self.assertEqual(done.returncode, 1)
        self.assertIn(f"docs/index.md:{line} R10 private-term #1", done.stdout)
        self.assertNotIn(term, done.stdout + done.stderr)
        self.assertEqual(done.stderr, "")
        env = {check.FORBIDDEN_ENV: str(terms)}
        done = self.cli("--root", str(self.fx.root), env=env)
        self.assertEqual(done.returncode, 1)
        self.assertNotIn(term, done.stdout + done.stderr)

    def test_help_runs_from_the_real_tool(self) -> None:
        done = self.cli("--help", script=SITE_DIR / "check.py")
        self.assertEqual(done.returncode, 0)
        self.assertIn("--extra-forbidden", done.stdout)
        self.assertIn("--root", done.stdout)


