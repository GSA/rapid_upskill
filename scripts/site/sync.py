"""Generate the site pages for images, prompts and scripts from their sources.

License: CC0-1.0 (public domain dedication,
https://creativecommons.org/publicdomain/zero/1.0/).

Standard library only, plus sitelib.py next to this file. No git call, no clock;
the repository is never derived from the current directory.

USAGE
    python3 -B scripts/site/sync.py [--root DIR] [--write] [--prune] [--check]

    (default)        print a plan (counts, then one line per create, update,
                     delete or stale path) and write nothing; exit 0
    --write          apply the plan
    --check          exit 1 on drift or stale files, 0 when clean
    --prune          with --write: also delete stale images and stale generated
                     pages; any other stale file is reported and never deleted.
                     Without --write it only reports what it would delete.
    --root DIR       repository root (default: two levels above this file)
    Exit 2: usage error (--check with --write or --prune), unreadable or invalid
    input. The message is "sync: <path>: <message>" on standard error.

PUBLIC API (frozen)
    compute_outputs(root: Path) -> dict[str, bytes]
        Keys are POSIX paths relative to root, in sorted order; values are the
        exact bytes to write (UTF-8, LF, one final newline for text). Raises
        InputError (issues: list of "path: message" strings) on invalid input.
    OWNED_DIRS   the folders this tool owns; a file there that compute_outputs
                 does not produce is stale.

SOURCES AND OUTPUTS
    images/**                          -> docs/assets/images/** (bytes copied)
    prompts/<code>/*.md                -> docs/prompts/<code>/<id>.md
    scripts/<code>/*.py, *.sh and
    scripts/common/*.py (stage OP)     -> docs/scripts/<code>/<id>.md
    plus docs/{prompts,scripts}/index.md always, and docs/<kind>/<code>/index.md
    for each stage that has at least one item.

CHOICES WHERE THE PLAN IS SILENT OR AMBIGUOUS
* IDs must read P-<code>-<nn> (prompts) or X-<code>-<nn> (scripts): nn has two
  digits (three only above 99), no sub-stage suffix. A prompt's `stage` and a
  script's optional `Stage` must equal the ID code; the ID code must match the
  folder (scripts/common counts as OP).
* Names of prompts and scripts use only letters, digits, ".", "_" and "-", since
  they reach a comment, a table cell and a URL. Dotfiles, README.md, names that
  start with "_" (and "test_" for scripts) are ignored.
* "Used in" ignores pages that are generated or that live inside OWNED_DIRS, so
  the outputs never depend on earlier outputs or on stale files. A page needs a
  non-empty string title to be listed. Pages are listed in path order; several
  pages are joined with ", ".
* An empty Needs or Placeholders cell reads "none". Optional Sub-stage, Inputs
  and Outputs rows are omitted when empty. kind and version are not shown.
  A script's Inputs and Outputs rows come after License.
* Index intros are fixed text. With no items the top-level index says so
  instead of showing an empty table.
* GENERATED comment on an index page names its source folder ("prompts/").
* A title may not contain "{{" or "{%" (it sits outside the raw block).
* A trailing "/" on source_repo_url is dropped before "/blob/".
* --prune deletes only image files under docs/assets/images and generated .md
  files. Emptied folders are removed only inside OWNED_DIRS, never the owned
  folder itself.
* Header and front matter text is plain text apart from backtick code spans.
  md_escape() backslash-escapes the backslash and the characters * _ [ ] < > |
  outside code spans in every metadata and index table cell (values and link
  text) and in every H1; fenced blocks and front matter are never escaped. In
  table cells a "|" inside a code span is escaped too, because it would split
  the cell. Newlines in a cell collapse to one space.
"""

